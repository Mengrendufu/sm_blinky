#ifndef PROJECT_LAYOUT_H_
#define PROJECT_LAYOUT_H_

// Shared by C, assembly and the preprocessed linker scripts.
// Keep numeric constants free of C-only suffixes for GNU ld.
#define PROJECT_FLASH_BASE  0x08000000
#define PROJECT_FLASH_BYTES 0x00080000
#define PROJECT_BOOT_BYTES  0x00004000
#define PROJECT_APP_BASE    (PROJECT_FLASH_BASE + PROJECT_BOOT_BYTES)
#define PROJECT_FLASH_END   (PROJECT_FLASH_BASE + PROJECT_FLASH_BYTES)
#define PROJECT_LOG_PAGE_BYTES 0x800
#define PROJECT_LOG_PAGES      2
#define PROJECT_LOG_BYTES      (PROJECT_LOG_PAGE_BYTES * PROJECT_LOG_PAGES)
#define PROJECT_LOG_BASE       (PROJECT_FLASH_END - PROJECT_LOG_BYTES)
#define PROJECT_APP_END        PROJECT_LOG_BASE
#define PROJECT_APP_BYTES      (PROJECT_APP_END - PROJECT_APP_BASE)
#define PROJECT_RAM_BASE    0x20000000
#define PROJECT_RAM_BYTES   0x00010000
#define PROJECT_RAM_END     (PROJECT_RAM_BASE + PROJECT_RAM_BYTES)
#define PROJECT_NOINIT_BYTES 32
#define PROJECT_FAULT_BYTES 128
#define PROJECT_NOINIT_BASE  (PROJECT_RAM_END - PROJECT_NOINIT_BYTES)
#define PROJECT_FAULT_BASE  (PROJECT_NOINIT_BASE - PROJECT_FAULT_BYTES)
#define PROJECT_BURN_MAGIC  0xB00710AD

#endif // PROJECT_LAYOUT_H_
